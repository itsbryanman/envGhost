#!/usr/bin/env bash
# Turn run.sh output into the markdown matrix in docs/harness-results.md.
#
#   tests/harness/render.sh results.tsv > docs/harness-results.md
set -euo pipefail

in=${1:?usage: render.sh results.tsv}

meta() { awk -F'\t' -v k="$1" '$1 == k { print $2 }' "$in"; }

cat <<EOF
# Harness results

Generated by \`tests/harness/run.sh\` and \`tests/harness/render.sh\`. Do not
edit by hand; rerun the harness instead.

| | |
|---|---|
| mode | $(meta mode) |
| kernel | $(meta kernel) |
| yama ptrace_scope | $(meta ptrace_scope) |
| ran as | $(meta user) |
| commit | $(meta commit) |
| date | $(meta date) |

HELD means the attack did not get the real secret (or, for the crash test,
the path did not get stuck). BYPASSED means it did. N/A means the attack
could not be attempted in this mode.

| Attack | Result | Notes |
|---|---|---|
EOF

awk -F'\t' '$1 == "RESULT" {
    attack = $4; note = $5
    gsub(/</, "\\&lt;", attack); gsub(/</, "\\&lt;", note)
    gsub(/\|/, "\\|", note)
    printf "| %s | %s | %s |\n", attack, $3, note
}' "$in"

held=$(awk -F'\t' '$1 == "RESULT" && $3 == "HELD"' "$in" | wc -l)
bypassed=$(awk -F'\t' '$1 == "RESULT" && $3 == "BYPASSED"' "$in" | wc -l)
na=$(awk -F'\t' '$1 == "RESULT" && $3 == "N/A"' "$in" | wc -l)
echo
echo "$held held, $bypassed bypassed, $na not applicable."
